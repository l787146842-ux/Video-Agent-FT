/** 新建 Skill 空白模板（六段式骨架）：头部含最小可注册 frontmatter
 *（注册侧必填即 name/description 非空，见 registry.py 注册校验）。
 * C1c 裁决 2026-08-31：书写约定提示随模板下发——frontmatter 仅
 * name/description 必填、其余键全部可选零警告；导入的外部 Skill
 *（如 裸键 skill_name:/skill_description: 无 --- 形态）同样可注册。
 * 2026-10-20 用户裁决：新建 Skill 每个章节要齐全——流程规划、素材分析、
 * 故事板设计、媒体生成、提示词写法、组装导出六段随模板下发（标题式），
 * 段名与后端阶段映射表一一对齐，保存后能力探针可完整识别。 */
export function blankSkillTemplate(): string {
  return [
    '---',
    'name: 新 Skill',
    'description: 一句话说明何时使用本 Skill',
    '---',
    '',
    '<!-- 书写约定：frontmatter 仅 name/description 必填，其余键全部可选；',
    '     流程纪律（何时暂停、何时确认）直接写进下方散文，平台不再读取机械声明键 -->',
    '',
    '# 新 Skill',
    '',
    '> 调用规则：一句话说明何时使用本 Skill',
    '',
    '## 流程规划',
    '',
    '1. 第一步做什么，调用哪个工具',
    '2. 第二步做什么，何时暂停等待用户确认',
    '',
    '## 素材分析',
    '',
    '- 看完素材要产出什么（例如：提取分镜、整理人物描述、基础裁切）',
    '',
    '## 故事板设计',
    '',
    '- 关键元素、分镜、音频层怎么建，每类要写哪些字段',
    '',
    '## 媒体生成',
    '',
    '- 出图/出视频/出音频时参考哪些素材，按什么顺序生成',
    '',
    '## 提示词写法',
    '',
    '- 提示词语言与内容规范（景别、运镜、时长等必须写清）',
    '',
    '## 组装导出',
    '',
    '- 时间线怎么组装、导出前要确认哪些内容',
    '',
  ].join('\n');
}
