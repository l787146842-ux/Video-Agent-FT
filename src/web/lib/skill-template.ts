/** 新建 Skill 空白模板：通用骨架 + 最小可注册 frontmatter。
 * frontmatter 仅 name/description 必填，其余键全部可选；流程纪律（何时暂停、
 * 何时确认）直接写进「制作流程」正文，平台不再读取机械声明键。 */
export function blankSkillTemplate(): string {
  return [
    '---',
    'name: 新 Skill',
    'description: 一句话说明何时使用本 Skill',
    '---',
    '',
    '# 新 Skill',
    '',
    '## 一、这个 Skill 做什么',
    '- 目标：解决什么问题。',
    '- 输入：用户会给什么（剧本、素材、参考图等）。',
    '- 交付：最后产出什么（分镜、图片、视频、成片等）。',
    '',
    '## 二、开工前先确认',
    '- 需要用户先提供或确认哪些信息（阶段、素材、语言、风格等）。',
    '',
    '## 三、制作流程',
    '1. 第一步做什么、产出什么。',
    '2. 第二步做什么，依赖哪一步。',
    '3. 后续步骤按同样方式补齐。',
    '',
    '**依赖关系：** 2→1。',
    '',
    '**何时暂停：** 每个关键阶段结束后停下来与用户确认，不要一口气跑完。',
    '',
    '## 四、结构与素材',
    '- 关键元素、分镜、音频怎么建，怎么命名、怎么引用。',
    '',
    '## 五、专业方法',
    '- 分类、拆解、检查清单等真正会改变产出质量的内容。',
    '',
    '## 六、参考资料',
    '- 需要时读 `references/…`（分册只在用到时读取）。',
    '',
  ].join('\n');
}
